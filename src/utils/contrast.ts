/** Utilidades de color: luminancia relativa y razón de contraste (WCAG 2). */

const HEX_RE = /^#([0-9a-f]{6})$/i;

export function isHexColor(value: string): boolean {
  return HEX_RE.test(value);
}

function channel(value: number): number {
  const c = value / 255;
  return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
}

export function luminance(hex: string): number {
  const n = Number.parseInt(hex.slice(1), 16);
  return 0.2126 * channel((n >> 16) & 255) + 0.7152 * channel((n >> 8) & 255) + 0.0722 * channel(n & 255);
}

/** Razón de contraste entre 1 (iguales) y 21 (negro sobre blanco). */
export function contrastRatio(a: string, b: string): number {
  const [light, dark] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (light + 0.05) / (dark + 0.05);
}

/** Contraste mínimo recomendado entre el código y el fondo. */
export const MIN_QR_CONTRAST = 4;
/** Por debajo de este valor es muy probable que el código no se lea. */
export const CRITICAL_QR_CONTRAST = 2.5;
